#!/usr/bin/env node
// Draws app-icon.svg: a stack of the same tiles the app shows for Blender
// versions (superellipse, tone gradient, offset Blender silhouette), seen in
// isometric projection, and file-icon.svg, the .blend file icon: a page with
// a folded corner in the release tile's look, built into icons/blend-file.ico.
// Run `npm run icon` to regenerate every icon size.
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Blender logo mark paths, shared with the UI component.
const markSource = readFileSync(join(root, "src/components/BlenderMark.tsx"), "utf8");
const markPaths = [...markSource.matchAll(/d="([^"]+)"/g)].map((m) => m[1]);
const MARK_VIEWBOX = { x: 212.4, y: -360.4, w: 58.5, h: 47.5 };

/** Lamé curve |x|^n + |y|^n = 1 filling a box. n = 5 matches `.glyph` in styles.css. */
function superellipse(x, y, size, n = 5, steps = 360) {
  const r = size / 2;
  const pts = [];
  for (let i = 0; i < steps; i++) {
    const t = (i / steps) * Math.PI * 2;
    const c = Math.cos(t);
    const s = Math.sin(t);
    pts.push([x + r + r * Math.sign(c) * Math.abs(c) ** (2 / n), y + r + r * Math.sign(s) * Math.abs(s) ** (2 / n)]);
  }
  return "M" + pts.map(([px, py]) => `${px.toFixed(2)} ${py.toFixed(2)}`).join("L") + "Z";
}

function mix(hex, other, amount) {
  const a = hex.match(/\w\w/g).map((h) => parseInt(h, 16));
  const b = other.match(/\w\w/g).map((h) => parseInt(h, 16));
  return "#" + a.map((v, i) => Math.round(v * amount + b[i] * (1 - amount)).toString(16).padStart(2, "0")).join("");
}

// Tile in local units 0..100, styled exactly like `.glyph`.
const TILE = superellipse(0, 0, 100);
const tones = [
  { id: "alpha", color: "#9b5cf6" },
  { id: "beta", color: "#0a84ff" },
  { id: "release", color: "#f07c12" },
];

// Isometric projection of the 100×100 tile: half-diagonals W (horizontal) and H.
// No backdrop: the stack itself is the icon and fills the canvas like the
// icons next to it on the taskbar. A superellipse (n = 5) reaches only
// 2^(-1/5) ≈ 0.87 of the way to its bounding-square corners, so the
// projected tile is sized by that, not by its square.
const REACH = 2 ** (-1 / 5);
const HALF_WIDTH = 482; // drawn half-width of a tile, out of 512
const W = HALF_WIDTH / REACH;
const H = W * 0.56;
const GAP = W * 0.327; // vertical distance between tiles
const DEPTH = W * 0.08; // tile thickness
const CX = 512;
const drawnHeight = 2 * H * REACH + 2 * GAP + DEPTH;
const topY = 512 - drawnHeight / 2 + H * REACH; // centre of the upper tile
const project = (cy) => `matrix(${(W / 100).toFixed(4)} ${(H / 100).toFixed(4)} ${(-W / 100).toFixed(4)} ${(H / 100).toFixed(4)} ${CX} ${(cy - H).toFixed(2)})`;

const defs = [];
const layers = [];
tones.forEach((tone, i) => {
  const cy = topY + (tones.length - 1 - i) * GAP;
  const light = mix(tone.color, "ffffff", 0.72);
  const dark = mix(tone.color, "000000", 0.8);
  const side = mix(tone.color, "000000", 0.55);
  // CSS linear-gradient(150deg, light, tone 55%, dark) across the tile.
  defs.push(`
    <linearGradient id="g-${tone.id}" gradientUnits="userSpaceOnUse" x1="15.85" y1="-9.15" x2="84.15" y2="109.15">
      <stop offset="0" stop-color="${light}"/>
      <stop offset="0.55" stop-color="${tone.color}"/>
      <stop offset="1" stop-color="${dark}"/>
    </linearGradient>`);

  // Soft shadow on the tile below.
  layers.push(`
  <g transform="translate(0 ${(DEPTH + 18).toFixed(1)})" filter="url(#shadow)" opacity="0.5">
    <path transform="${project(cy)}" d="${TILE}" fill="#000"/>
  </g>`);
  // Thickness: the face swept downwards.
  const sweep = [];
  for (let d = Math.round(DEPTH); d > 0; d -= 2) sweep.push(`<path transform="translate(0 ${d}) ${project(cy)}" d="${TILE}"/>`);
  layers.push(`
  <g fill="${side}">${sweep.join("")}</g>`);
  // Face: gradient, offset Blender silhouette (as in `.glyph-mark`), gloss.
  const markScale = 124 / MARK_VIEWBOX.w;
  layers.push(`
  <g transform="${project(cy)}">
    <path d="${TILE}" fill="url(#g-${tone.id})"/>
    <g clip-path="url(#tile)">
      <g transform="translate(-6 22) scale(${markScale.toFixed(5)}) translate(${-MARK_VIEWBOX.x} ${-MARK_VIEWBOX.y})" fill="#000" fill-opacity="0.22">
        ${markPaths.map((d) => `<path d="${d}"/>`).join("\n        ")}
      </g>
      <rect width="100" height="50" fill="url(#gloss)"/>
    </g>
  </g>`);
});

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- Generated by scripts/icon.mjs — edit the script, not this file. -->
  <defs>
    <linearGradient id="gloss" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.18"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
    <clipPath id="tile"><path d="${TILE}"/></clipPath>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur stdDeviation="16"/>
    </filter>${defs.join("")}
  </defs>
${layers.join("")}
</svg>
`;

writeFileSync(join(root, "app-icon.svg"), svg);
writeFileSync(join(root, "src/assets/logo.svg"), svg);
console.log("app-icon.svg written");

// ── .blend file icon ──
// A page with its top-right corner folded down, sized like the document
// icons Explorer shows next to it. Its face is the release tile: the orange
// gradient, the offset dark Blender silhouette and the gloss.
const PAGE = { x: 40, y: 12, w: 176, h: 232, r: 22, fold: 62 };
const right = PAGE.x + PAGE.w;
const bottom = PAGE.y + PAGE.h;
const foldX = right - PAGE.fold;
const foldY = PAGE.y + PAGE.fold;
const { r } = PAGE;
const page = [
  `M${PAGE.x + r} ${PAGE.y}`,
  `H${foldX}`,
  `L${right} ${foldY}`,
  `V${bottom - r}`,
  `A${r} ${r} 0 0 1 ${right - r} ${bottom}`,
  `H${PAGE.x + r}`,
  `A${r} ${r} 0 0 1 ${PAGE.x} ${bottom - r}`,
  `V${PAGE.y + r}`,
  `A${r} ${r} 0 0 1 ${PAGE.x + r} ${PAGE.y}`,
  "Z",
].join(" ");
// The folded-down corner: the back of the page, rounded where it creases.
const crease = 14;
const flap = `M${foldX} ${PAGE.y} V${foldY - crease} Q${foldX} ${foldY} ${foldX + crease} ${foldY} H${right} Z`;

const release = tones.find((t) => t.id === "release").color;
// CSS linear-gradient(150deg, …) across the page box.
const angle = (150 * Math.PI) / 180;
const [dx, dy] = [Math.sin(angle), -Math.cos(angle)];
const span = (Math.abs(PAGE.w * dx) + Math.abs(PAGE.h * dy)) / 2;
const [cx, cy] = [PAGE.x + PAGE.w / 2, PAGE.y + PAGE.h / 2];
const fmt = (n) => n.toFixed(2);

// The silhouette sits as on a tile (124 % wide, shifted left and down) and is
// cut off by the bottom of the page.
const markW = PAGE.w * 1.24;
const markH = (markW * MARK_VIEWBOX.h) / MARK_VIEWBOX.w;
const markX = PAGE.x - PAGE.w * 0.06;
const markY = bottom - markH * 0.78;

const fileSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
  <!-- Generated by scripts/icon.mjs — edit the script, not this file. -->
  <defs>
    <linearGradient id="face" gradientUnits="userSpaceOnUse" x1="${fmt(cx - dx * span)}" y1="${fmt(cy - dy * span)}" x2="${fmt(cx + dx * span)}" y2="${fmt(cy + dy * span)}">
      <stop offset="0" stop-color="${mix(release, "ffffff", 0.72)}"/>
      <stop offset="0.55" stop-color="${release}"/>
      <stop offset="1" stop-color="${mix(release, "000000", 0.8)}"/>
    </linearGradient>
    <linearGradient id="back" gradientUnits="userSpaceOnUse" x1="${foldX}" y1="${foldY}" x2="${fmt(foldX + PAGE.fold / 2)}" y2="${fmt(PAGE.y + PAGE.fold / 2)}">
      <stop offset="0" stop-color="${mix(release, "ffffff", 0.42)}"/>
      <stop offset="1" stop-color="${mix(release, "ffffff", 0.68)}"/>
    </linearGradient>
    <linearGradient id="gloss" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.2"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
    <clipPath id="page"><path d="${page}"/></clipPath>
    <filter id="soft" x="-30%" y="-30%" width="160%" height="160%">
      <feGaussianBlur stdDeviation="5"/>
    </filter>
  </defs>
  <path d="${page}" fill="url(#face)"/>
  <g clip-path="url(#page)">
    <g transform="translate(${fmt(markX)} ${fmt(markY)}) scale(${(markW / MARK_VIEWBOX.w).toFixed(5)}) translate(${-MARK_VIEWBOX.x} ${-MARK_VIEWBOX.y})" fill="#000" fill-opacity="0.22">
      ${markPaths.map((d) => `<path d="${d}"/>`).join("\n      ")}
    </g>
    <rect x="${PAGE.x}" y="${PAGE.y}" width="${PAGE.w}" height="${PAGE.h / 2}" fill="url(#gloss)"/>
    <path d="${flap}" transform="translate(-5 7)" fill="#000" opacity="0.35" filter="url(#soft)"/>
  </g>
  <path d="${flap}" fill="url(#back)"/>
</svg>
`;
writeFileSync(join(root, "file-icon.svg"), fileSvg);

// Every Windows icon size from the SVG, rendered by the Tauri CLI.
const out = mkdtempSync(join(tmpdir(), "blendstack-file-icon-"));
try {
  execSync(`npx tauri icon file-icon.svg -o "${out}"`, { cwd: root, stdio: "ignore" });
  copyFileSync(join(out, "icon.ico"), join(root, "src-tauri/icons/blend-file.ico"));
} finally {
  rmSync(out, { recursive: true, force: true });
}
console.log("file-icon.svg and icons/blend-file.ico written");
